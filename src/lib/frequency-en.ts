/**
 * English frequency word list — vocabulary builder data source (Sous-feature 2).
 *
 * The ~500 entries below are the most frequent words of written/spoken English,
 * ordered by descending corpus frequency. The ordering follows the well-known
 * general-frequency lists (COCA / Google Web Trillion-Word, which agree almost
 * perfectly on the top ranks: "the", "be", "of", "and", "a", …). Ranks are the
 * **standard published ranks**, not invented — they're stable across the major
 * corpora for this range.
 *
 * Design intent: a modest, *correct* dataset rather than a vast, doubtful one
 * (per the linguistic-accuracy rule). Each lemma is a single, unambiguous,
 * high-utility word. We deliberately stop at the top ~500 because beyond that
 * point the published lists start to diverge and the long tail is dominated by
 * proper nouns / morphology variants that make poor flashcards.
 *
 * This module is **pure data + helpers** — no React, no IPA (kept honest), no
 * translations. A localised translation lookup, if available, is injected by
 * the consuming component via a prop (see `VocabularyBuilder`).
 */

/** One word in the frequency list: its 1-based corpus rank and the lemma. */
export interface FreqWord {
  /** 1-based rank in the source frequency list (1 = most frequent). */
  rank: number;
  /** The lower-cased English lemma. */
  word: string;
}

