/**
 * The exported frequency list — one `{ rank, word }` per lemma, in descending
 * frequency order (rank 1 first).
 */
export const FREQUENCY_EN: FreqWord[] = WORDS.map((word, index) => ({
  rank: index + 1,
  word,
}));

/**
 * Every word whose rank is ≤ `maxRank`, in ascending-rank order. Clamps to the
 * list bounds, so a `maxRank` larger than the list simply returns everything
 * and a non-positive bound returns an empty array.
 */
export function wordsInBand(maxRank: number): FreqWord[] {
  if (!Number.isFinite(maxRank) || maxRank <= 0) return [];
  return FREQUENCY_EN.filter((entry) => entry.rank <= maxRank);
}
